def mir(H,W):
    import copy
    f=lambda p:(W-p[0],p[1])
    G=copy.deepcopy(H)
    x0,y0,x1,y1=H['box']; G['box']=(W-x1,y0,W-x0,y1)
    G['wrist']=[f(p) for p in H['wrist']][::-1]; G['inside']=f(H['inside'])
    G['seeds']=[f(p) for p in H['seeds']]
    G['fingers']={k:[f(p) for p in v] for k,v in H['fingers'].items()}
    G['palm_seed']=[f(p) for p in H['palm_seed']]
    if 'loose' in H: G['loose']=[f(p) for p in H['loose']]
    return G
